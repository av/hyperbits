const listBitJsonFiles = async (dirPath) => {
  const entries = await readdir(dirPath, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(dirPath, entry.name);
      if (entry.isDirectory()) {
        return listBitJsonFiles(fullPath);
      }
      if (entry.isFile() && entry.name === "bit.json") {
        return [fullPath];
      }
      return [];
    }),
  );
  return files.flat().sort((left, right) => left.localeCompare(right));
};

export const parseCompositionVariables = (html) => {
  const match = html.match(VARIABLES_ATTR);
  if (!match) {
    return [];
  }

  try {
    const parsed = JSON.parse(match[2]);
    if (!Array.isArray(parsed)) {
      return [];
    }
    return parsed.filter(
      (entry) =>
        typeof entry === "object" &&
        entry !== null &&
        typeof entry.id === "string",
    );
  } catch {
    return [];
  }
};

const formatDefault = (value) => {
  if (value === undefined) {
    return "";
  }
  if (typeof value === "string") {
    return JSON.stringify(value);
  }
  return JSON.stringify(value);
};

const formatKnob = (variable) => {
  const typeLabel = variable.type ? String(variable.type) : "unknown";
  const defaultLabel =
    variable.default === undefined
      ? ""
      : `, default ${formatDefault(variable.default)}`;
  const nameLabel =
    typeof variable.label === "string" && variable.label.trim().length > 0
      ? ` — ${variable.label}`
      : "";
  return `\`${variable.id}\` (${typeLabel}${defaultLabel})${nameLabel}`;
};

const slugify = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const compactText = (value) =>
  value
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|\s)\/\/.*$/gm, "$1")
    .replace(/\s+/g, " ")
    .replace(/=\s*\|/g, "=")
    .trim();

const isExported = (node) =>
  Boolean(
    node.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
    ),
  );

const isPrivateMember = (node) =>
  Boolean(
    node.modifiers?.some(
      (modifier) =>
        modifier.kind === ts.SyntaxKind.PrivateKeyword ||
        modifier.kind === ts.SyntaxKind.ProtectedKeyword,
    ),
  );

const unwrapExpression = (node) => {
  if (ts.isAsExpression(node) || ts.isSatisfiesExpression(node)) {
    return unwrapExpression(node.expression);
  }
  if (ts.isParenthesizedExpression(node)) {
    return unwrapExpression(node.expression);
  }
  return node;
};

const functionSignature = (name, node) => {
  const typeParams = node.typeParameters
    ? `<${node.typeParameters.map((param) => compactText(param.getText())).join(", ")}>`
    : "";
  const params = node.parameters
    .map((param) => compactText(param.getText()))
    .join(", ");
  const returnType = node.type ? `: ${compactText(node.type.getText())}` : "";
  return `${name}${typeParams}(${params})${returnType}`;
};

const objectLiteralKeys = (node) => {
  const expression = unwrapExpression(node);
  if (!ts.isObjectLiteralExpression(expression)) {
    return [];
  }
  return expression.properties
    .map((property) => {
      if (
        ts.isPropertyAssignment(property) ||
        ts.isMethodDeclaration(property)
      ) {
        return property.name?.getText();
      }
      if (ts.isShorthandPropertyAssignment(property)) {
        return property.name.getText();
      }
      return undefined;
    })
    .filter(Boolean);
};

const collectClassMembers = (node) => {
  const members = [];
  for (const member of node.members) {
    if (isPrivateMember(member)) {
      continue;
    }
    if (ts.isConstructorDeclaration(member)) {
      const params = member.parameters
        .map((param) => compactText(param.getText()))
        .join(", ");
      members.push(`constructor(${params})`);
      continue;
    }
    if (
      ts.isMethodDeclaration(member) &&
      member.name &&
      !ts.isPrivateIdentifier(member.name)
    ) {
      const staticPrefix = member.modifiers?.some(
        (modifier) => modifier.kind === ts.SyntaxKind.StaticKeyword,
      )
        ? "static "
        : "";
      members.push(
        `${staticPrefix}${functionSignature(member.name.getText(), member)}`,
      );
    }
  }
  return members;
};

export const extractExportedApis = (fileName, source) => {
  const sourceFile = ts.createSourceFile(
    fileName,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const apis = [];

  const visit = (node) => {
    if (ts.isExportDeclaration(node)) {
      return;
    }

    if (!isExported(node)) {
      if (ts.isModuleBlock(node) || ts.isSourceFile(node)) {
        ts.forEachChild(node, visit);
      }
      return;
    }

    if (ts.isFunctionDeclaration(node) && node.name) {
      apis.push({
        kind: "function",
        name: node.name.text,
        signature: functionSignature(node.name.text, node),
      });
      return;
    }

    if (ts.isClassDeclaration(node) && node.name) {
      apis.push({
        kind: "class",
        name: node.name.text,
        signature: `class ${node.name.text}`,
        members: collectClassMembers(node),
      });
      return;
    }

    if (ts.isTypeAliasDeclaration(node)) {
      apis.push({
        kind: "type",
        name: node.name.text,
        signature: compactText(node.getText()).replace(/^export /, ""),
      });
      return;
    }

    if (ts.isInterfaceDeclaration(node)) {
      apis.push({
        kind: "interface",
        name: node.name.text,
        signature: compactText(node.getText()).replace(/^export /, ""),
      });
      return;
    }

    if (ts.isVariableStatement(node)) {
      for (const declaration of node.declarationList.declarations) {
        if (!ts.isIdentifier(declaration.name)) {
          continue;
        }
        const name = declaration.name.text;
        const initializer = declaration.initializer
          ? unwrapExpression(declaration.initializer)
          : undefined;
        const declaredType = declaration.type
          ? compactText(declaration.type.getText())
          : "";

        if (
          declaredType &&
          initializer &&
          (ts.isArrowFunction(initializer) ||
            ts.isFunctionExpression(initializer))
        ) {
          apis.push({
            kind: "function",
            name,
            signature: `${name}: ${declaredType}`,
          });
          continue;
        }

        if (initializer && ts.isArrowFunction(initializer)) {
          apis.push({
            kind: "function",
            name,
            signature: `${name} = ${functionSignature("", initializer)}`,
          });
          continue;
        }

        if (initializer && ts.isFunctionExpression(initializer)) {
          apis.push({
            kind: "function",
            name,
            signature: functionSignature(name, initializer),
          });
          continue;
        }

        const keys = initializer ? objectLiteralKeys(initializer) : [];
        if (keys.length > 0) {
          apis.push({
            kind: "const",
            name,
            signature: `const ${name}`,
            members: keys,
          });
          continue;
        }

        const typeText = declaration.type
          ? `: ${compactText(declaration.type.getText())}`
          : "";
        const valueText = declaration.initializer
          ? compactText(declaration.initializer.getText())
          : "";
        apis.push({
          kind: "const",
          name,
          signature: valueText
            ? `const ${name}${typeText} = ${valueText}`
            : `const ${name}${typeText}`,
        });
      }
    }
  };

  ts.forEachChild(sourceFile, visit);
  return apis;
};

const renderApiBlock = (api) => {
  const lines = [`### \`${api.name}\``, ""];
  if (api.kind === "class") {
    lines.push("```ts", api.signature, "```", "");
    if (api.members?.length) {
      lines.push("Members:", "");
      for (const member of api.members) {
        lines.push(`- \`${member}\``);
      }
      lines.push("");
    }
    return lines;
  }
  if (api.kind === "const" && api.members?.length) {
    lines.push("```ts", api.signature, "```", "");
    lines.push(
      "Keys: " + api.members.map((key) => `\`${key}\``).join(", "),
      "",
    );
    return lines;
  }
  lines.push("```ts", api.signature, "```", "");
  return lines;
};

const renderHelpersMarkdown = (sections) => {
  const toc = sections
    .map((section) => `- [${section.title}](#${slugify(section.title)})`)
    .join("\n");

  const body = sections
    .map((section) => {
      const importPath =
        section.id === "package"
          ? "hyperbits/helpers"
          : `hyperbits/helpers/${section.id}`;
      const lines = [
        `## ${section.title}`,
        "",
        `ESM: \`import { ... } from "${importPath}"\`. IIFE: \`hyperbits.<name>(...)\`.`,
        "",
      ];
      for (const api of section.apis) {
        lines.push(...renderApiBlock(api));
      }
      const example = HELPER_EXAMPLES[section.id];
      if (example) {
        lines.push("Example:", "", "```js", example, "```", "");
      }
      return lines.join("\n");
    })
    .join("\n");

  return [
    "# Helpers reference",
    "",
    GENERATED_BANNER,
    "",
    "Bits load helpers from the IIFE global `hyperbits` after GSAP:",
    "",
    "```html",
    `<script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>`,
    `<script src="https://unpkg.com/hyperbits/dist/hyperbits.iife.js"></script>`,
    "```",
    "",
    "ESM consumers import from `hyperbits/helpers` or `hyperbits/helpers/<name>`.",
    "",
    "## Table of contents",
    toc,
    "",
    body.trimEnd(),
    "",
  ].join("\n");
};

const renderBitsMarkdown = (bits) => {
  const grouped = new Map();
  for (const category of CATEGORY_ORDER) {
    grouped.set(category, []);
  }

  for (const bit of bits) {
    const bucket = grouped.get(bit.category) ?? [];
    bucket.push(bit);
    grouped.set(bit.category, bucket);
  }

  for (const bucket of grouped.values()) {
    bucket.sort((left, right) => left.id.localeCompare(right.id));
  }

  const toc = CATEGORY_ORDER.map((category) => {
    const label = CATEGORY_LABELS[category] ?? category;
    return `- [${label}](#${slugify(label)})`;
  }).join("\n");

  const sections = CATEGORY_ORDER.map((category) => {
    const label = CATEGORY_LABELS[category] ?? category;
    const bucket = grouped.get(category) ?? [];
    const lines = [`## ${label}`, ""];
    if (bucket.length === 0) {
      lines.push("_No bits in this category._", "");
      return lines.join("\n");
    }
    for (const bit of bucket) {
      lines.push(`### \`${bit.id}\``, "", bit.description, "");
      lines.push(`- Path: \`${bit.sourcePath}\``);
      lines.push(`- Title: ${bit.title}`);
      lines.push(
        `- Size: ${bit.width}x${bit.height}, duration ${bit.duration}s`,
      );
      lines.push(
        `- Helpers: ${
          bit.helpers.length > 0
            ? bit.helpers.map((name) => `\`${name}\``).join(", ")
            : "none"
        }`,
      );
      if (bit.knobs.length === 0) {
        lines.push("- Knobs (`data-composition-variables`): none");
      } else {
        lines.push("- Knobs (`data-composition-variables`):");
        for (const knob of bit.knobs) {
          lines.push(`  - ${formatKnob(knob)}`);
        }
      }
      lines.push("");
    }
    return lines.join("\n");
  }).join("\n");

  return [
    "# Bits catalog",
    "",
    GENERATED_BANNER,
    "",
    `Count: ${bits.length} bits across ${CATEGORY_ORDER.length} categories.`,
    "",
    "## Table of contents",
    toc,
    "",
    sections.trimEnd(),
    "",
  ].join("\n");
};

export const loadHelperSections = async () => {
  const sections = [];
  for (const section of HELPER_SECTIONS) {
    const apis = [];
    const seen = new Set();
    for (const relativePath of section.files) {
      const filePath = path.join(helpersRoot, relativePath);
      const source = await readFile(filePath, "utf8");
      for (const api of extractExportedApis(relativePath, source)) {
        if (seen.has(api.name)) {
          continue;
        }
        seen.add(api.name);
        apis.push(api);
      }
    }
    sections.push({
      id: section.id,
      title: section.title,
      apis,
    });
  }
  return sections;
};

export const loadSkillBits = async () => {
  const bitFiles = await listBitJsonFiles(bitsRoot);
  const bits = [];

  for (const bitJsonPath of bitFiles) {
    const manifest = JSON.parse(await readFile(bitJsonPath, "utf8"));
    const bitDir = path.dirname(bitJsonPath);
    const category = path.basename(path.dirname(bitDir));
    const htmlPath = path.join(bitDir, "index.html");
    const html = await readFile(htmlPath, "utf8");
    const sourcePath = path
      .relative(projectRoot, htmlPath)
      .split(path.sep)
      .join("/");

    bits.push({
      id: manifest.name,
      title: manifest.title,
      description: manifest.description,
      category,
      helpers: [...(manifest.helpers ?? [])],
      duration: manifest.duration,
      width: manifest.width,
      height: manifest.height,
      sourcePath,
      knobs: parseCompositionVariables(html),
    });
  }

  return bits;
};

export const generateSkillRefs = async () => {
  const [bits, helperSections] = await Promise.all([
    loadSkillBits(),
    loadHelperSections(),
  ]);

  await mkdir(skillRefsDir, { recursive: true });
  const bitsMarkdown = renderBitsMarkdown(bits);
  const helpersMarkdown = renderHelpersMarkdown(helperSections);
  await writeFile(bitsMdPath, bitsMarkdown);
  await writeFile(helpersMdPath, helpersMarkdown);

  return {
    bits,
    helperSections,
    bitsMarkdown,
    helpersMarkdown,
    bitsMdPath,
    helpersMdPath,
  };
};

const main = async () => {
  const result = await generateSkillRefs();
  console.log(
    `Generated skill refs: ${result.bits.length} bit(s), ${result.helperSections.length} helper section(s).`,
  );
};

if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  });
}
